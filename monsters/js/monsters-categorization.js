// Apply categorization to allMonsters
function applyMonsterCategorization() {
    if (typeof allMonsters === 'undefined') return;
    
    for (const [key, data] of Object.entries(MONSTER_CATEGORIZATION)) {
        if (allMonsters[key]) {
            // Only add if not already present
            if (!allMonsters[key].environment) {
                allMonsters[key].environment = data.environment;
            }
            if (!allMonsters[key].role) {
                allMonsters[key].role = data.role;
            }
            if (!allMonsters[key].tags || allMonsters[key].tags.length === 0) {
                allMonsters[key].tags = data.tags;
            }
        }
    }
    
    console.log(`Applied categorization to ${Object.keys(MONSTER_CATEGORIZATION).length} monsters`);
}

// Run after page loads
if (typeof document !== 'undefined') {
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', applyMonsterCategorization);
    } else {
        // DOMContentLoaded has already fired, run immediately
        setTimeout(applyMonsterCategorization, 100);
    }
}
